struct canvas
  {int                       w;
   int                       h;
   bool                      bitmap;          /* depth 1: pixels 0 or 1 */
   std::vector<unsigned int> px;              /* 0x00RRGGBB             */

   canvas (int cw, int ch, bool bm, unsigned int fill)
     : w (std::max (0, cw)), h (std::max (0, ch)), bitmap (bm),
       px ((size_t) std::max (0, cw) * (size_t) std::max (0, ch), fill)
     {}

   bool inside (int x, int y) const
     {return x >= 0 && y >= 0 && x < w && y < h;
     }

   unsigned int &at (int x, int y)
     {return px [(size_t) y * w + x];
     }
  };

static std::vector<canvas *> pixmaps (1, (canvas *) NULL);  /* 0 = None */
static std::vector<Pixmap>   free_pixmaps;

static Pixmap new_pixmap (canvas *c)
  {if (! free_pixmaps.empty ())
      {Pixmap p = free_pixmaps.back ();

       free_pixmaps.pop_back ();
       pixmaps [p] = c;
       return p;
      }
   pixmaps.push_back (c);
   return pixmaps.size () - 1;
  }

static canvas *pixmap_canvas (Pixmap p)
  {return (p > 0 && p < pixmaps.size ()) ? pixmaps [p] : NULL;
  }

