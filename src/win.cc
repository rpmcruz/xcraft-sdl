int win::win_color (int r, int g, int b)
  {if (r == last_r && g == last_g && b == last_b)
      return last_best_color;

   double best_dist  = DBL_MAX;
   int    best_color = 0;

   for (int i = 1; i < max_colors; i++)
     {int dr = color_r [i] - r;
      int dg = color_g [i] - g;
      int db = color_b [i] - b;
      int d  = dr * dr + dg * dg + db * db;

      if (d < best_dist)
         {best_dist  = d;
          best_color = i;
         }
     }
   if (r*r + g*g + b*b < best_dist)
      {best_dist  = r*r + g*g + b*b;
       best_color = 63;
      }
   if ((255-r)*(255-r) + (255-g)*(255-g) + (255-b)*(255-b) < best_dist)
      best_color = 0;
   last_r          = r;
   last_g          = g;
   last_b          = b;
   last_best_color = best_color;
   return best_color;
  }

