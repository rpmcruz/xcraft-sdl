  {if (is_enable)
      {disable_tree (this);
       if   (parent_win != NULL)
            {std::vector<win *> &l = kids [parent_win];

             l.erase (std::remove (l.begin (), l.end (), this), l.end ());
            }
       else {top_windows.erase (std::remove (top_windows.begin (),
                                             top_windows.end (), this),
                                top_windows.end ());
             layout ();
            }
       if (hover_win == NULL && sdl_ready)
          set_hover (window_at (top_windows, ptr_x, ptr_y));
       mark_dirty ();
      }
   forget (this);
   delete surface;
   surface = NULL;
  }

