enum {clip_none, clip_rects, clip_bitmap};

static unsigned int raster_op (int f, unsigned int src, unsigned int dst)
  {switch (f)
     {case 0x0 : return 0;
      case 0x1 : return src & dst;
      case 0x2 : return src & ~dst;
      case 0x3 : return src;
      case 0x4 : return ~src & dst;
      case 0x5 : return dst;
      case 0x6 : return src ^ dst;
      case 0x7 : return src | dst;
      case 0x8 : return ~(src | dst);
      case 0x9 : return ~src ^ dst;
      case 0xa : return ~dst;
      case 0xb : return src | ~dst;
      case 0xc : return ~src;
      case 0xd : return ~src | dst;
      case 0xe : return ~(src & dst);
      default  : return ~0u;
     }
  }

static inline bool clip_ok (const win *w, int x, int y)
  {switch (w->clip_mode)
     {case clip_rects :
        return x >= w->clip_x && x < w->clip_x + w->clip_dx &&
               y >= w->clip_y && y < w->clip_y + w->clip_dy;
      case clip_bitmap :
        {canvas *m = pixmap_canvas (w->clip_mask);
         int    mx = x - w->clip_x;
         int    my = y - w->clip_y;

         return m == NULL || (m->inside (mx, my) && m->at (mx, my) != 0);
        }
      default :
        return true;
     }
  }

static inline void put (win *w, canvas *c, int x, int y, unsigned int p)
  {if (! c->inside (x, y) || ! clip_ok (w, x, y))
      return;

   unsigned int &d = c->at (x, y);

   if   (w->gc_function == GXcopy)
        d = p;
   else d = raster_op (w->gc_function, p, d);
   d &= c->bitmap ? 1u : 0xffffffu;
  }

static void fill_rect (win *w, canvas *c, int x, int y, int dx, int dy,
                       unsigned int p)
  {int x0 = std::max (0, x);
   int y0 = std::max (0, y);
   int x1 = std::min (c->w, x + dx);
   int y1 = std::min (c->h, y + dy);

   if (w->gc_function == GXcopy && w->clip_mode == clip_none && ! c->bitmap)
      {for (int yy = y0; yy < y1; yy++)
         std::fill (&c->at (0, yy) + x0, &c->at (0, yy) + x1, p);
       return;
      }
   for (int yy = y0; yy < y1; yy++)
     for (int xx = x0; xx < x1; xx++)
       put (w, c, xx, yy, p);
  }

static void draw_line (win *w, canvas *c, int x1, int y1, int x2, int y2,
                       bool last = true)
  {int dx  = abs (x2 - x1);
   int dy  = -abs (y2 - y1);
   int sx  = (x1 < x2) ? 1 : -1;
   int sy  = (y1 < y2) ? 1 : -1;
   int err = dx + dy;

   for (;;)
     {bool end = (x1 == x2 && y1 == y2);

      if (! end || last)
         put (w, c, x1, y1, w->fg_pixel);
      if (end)
         break;

      int e2 = 2 * err;

      if (e2 >= dy) {err += dy; x1 += sx;}
      if (e2 <= dx) {err += dx; y1 += sy;}
     }
  }

/* XCopyArea; a depth 1 source is drawn like XCopyPlane (fg/bg)         */

static void copy_area (win *w, canvas *src, canvas *dst,
                       int sx, int sy, int dx, int dy, int tx, int ty)
  {if (src == NULL || dst == NULL || dx <= 0 || dy <= 0)
      return;

   bool                      plane = src->bitmap && ! dst->bitmap;
   std::vector<unsigned int> tmp;
   const unsigned int        *s    = &src->px [0];
   int                       sw    = src->w;

   if (src == dst)
      {tmp = src->px;
       s   = &tmp [0];
      }
   for (int j = 0; j < dy; j++)
     {int y = sy + j;

      if (y < 0 || y >= src->h)
         continue;
      for (int i = 0; i < dx; i++)
        {int x = sx + i;

         if (x < 0 || x >= src->w)
            continue;

         unsigned int p = s [(size_t) y * sw + x];

         if (plane)
            p = p ? w->fg_pixel : w->bg_pixel;
         put (w, dst, tx + i, ty + j, p);
        }
     }
  }

