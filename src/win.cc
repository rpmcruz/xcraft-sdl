/*= win.cc -- SDL2 back end of CRAFT's window layer                    =*/
/*=                                                                    =*/
/*= This file replaces win.hc, the Xlib implementation of class win in =*/
/*= the original CRAFT 3.5 sources (Uwe Beyer, GMD, 1993-1997).        =*/
/*= Changed 2026-11-22 for the xcraft-sdl port:                        =*/
/*=  - every X window (top level or child) is a software canvas; all   =*/
/*=    of them are composited into one resizable SDL window;           =*/
/*=  - drawing (points, lines, rectangles, bitmaps, pixmaps, raster    =*/
/*=    functions such as XOR, clip rectangles and clip masks, image    =*/
/*=    text) is done in software following the X11 GC rules;          =*/
/*=  - text uses the public domain misc-fixed fonts, cursors the X     =*/
/*=    cursor font glyphs (both generated by scripts in tools/);      =*/
/*=  - input is routed like X does it: to the deepest window under the =*/
/*=    pointer, with an implicit grab while a mouse button is held.    =*/
/*= The interface in win.h is the original one.                        =*/
/*======================================================================*/

