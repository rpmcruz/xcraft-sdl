static void sdl_core_init ()
  {if (sdl_ready)
      return;
   SDL_SetHint (SDL_HINT_APP_NAME,    "xcraft");
   SDL_SetHint (SDL_HINT_VIDEODRIVER, "wayland,x11");   /* Wayland first */
   if (SDL_Init (SDL_INIT_VIDEO | SDL_INIT_TIMER) != 0)
      {SDL_SetHint (SDL_HINT_VIDEODRIVER, "");   /* SDL < 2.0.22: no lists */
       if (SDL_Init (SDL_INIT_VIDEO | SDL_INIT_TIMER) != 0)
          {fprintf (stderr, "xcraft: SDL_Init failed: %s\n", SDL_GetError ());
           exit (1);
          }
      }
   atexit (SDL_Quit);
   sdl_ready = true;
  }

static int initial_scale ()
  {const char *s = getenv ("XCRAFT_SCALE");

   return (s != NULL && atoi (s) > 0) ? atoi (s) : 0;
  }

static void fit_window ()
  {if (sdl_win == NULL || user_sized || desk_w <= 0 || desk_h <= 0)
      return;
   if (SDL_GetWindowFlags (sdl_win) &
       (SDL_WINDOW_FULLSCREEN | SDL_WINDOW_FULLSCREEN_DESKTOP |
        SDL_WINDOW_MAXIMIZED))
      return;

   int      s = initial_scale ();
   SDL_Rect usable;

   if (s == 0)
      {s = 1;
       if (SDL_GetDisplayUsableBounds (SDL_GetWindowDisplayIndex (sdl_win),
                                       &usable) == 0)
          while (desk_w * (s + 1) <= usable.w * 9 / 10 &&
                 desk_h * (s + 1) <= usable.h * 9 / 10)
            s++;
      }
   req_w = desk_w * s;
   req_h = desk_h * s;

   int ww;
   int wh;

   SDL_GetWindowSize (sdl_win, &ww, &wh);
   if (ww != req_w || wh != req_h)
      {SDL_SetWindowSize (sdl_win, req_w, req_h);
       if (! shown)
          SDL_SetWindowPosition (sdl_win, SDL_WINDOWPOS_CENTERED,
                                          SDL_WINDOWPOS_CENTERED);
      }
  }

static void open_sdl_window ()
  {if (sdl_win != NULL)
      return;
   sdl_core_init ();
   sdl_win = SDL_CreateWindow ("xcraft",
                               SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
                               std::max (desk_w, 100), std::max (desk_h, 100),
                               SDL_WINDOW_RESIZABLE | SDL_WINDOW_HIDDEN |
                               SDL_WINDOW_ALLOW_HIGHDPI);
   if (sdl_win == NULL)
      {fprintf (stderr, "xcraft: cannot open window: %s\n", SDL_GetError ());
       exit (1);
      }
   renderer = SDL_CreateRenderer (sdl_win, -1, SDL_RENDERER_ACCELERATED);
   if (renderer == NULL)
      renderer = SDL_CreateRenderer (sdl_win, -1, SDL_RENDERER_SOFTWARE);
   if (renderer == NULL)
      {fprintf (stderr, "xcraft: cannot create renderer: %s\n",
                SDL_GetError ());
       exit (1);
      }
   for (size_t i = 0; i < sizeof (cursors) / sizeof (cursors [0]); i++)
     {const x_cursor_glyph &g = x_cursor_glyphs [i];

      cursors [i] = SDL_CreateCursor (g.data, g.mask, g.w, g.h,
                                      g.hot_x, g.hot_y);
     }
   SDL_StartTextInput ();
   fit_window ();
  }

static void abs_pos (win *w, int &ax, int &ay)
  {ax = 0;
   ay = 0;
   for (win *v = w; v != NULL; v = v->parent_win)
     {ax += v->pos_x;
      ay += v->pos_y;
     }
  }

static win *window_at (const std::vector<win *> &list, int x, int y)
  {for (int i = (int) list.size () - 1; i >= 0; i--)
     {win *w = list [i];

      if (w->is_enable &&
          x >= w->pos_x && x < w->pos_x + w->w_dx &&
          y >= w->pos_y && y < w->pos_y + w->w_dy)
         {std::map<win *, std::vector<win *> >::iterator k = kids.find (w);

          if (k != kids.end ())
             {win *c = window_at (k->second, x - w->pos_x, y - w->pos_y);

              if (c != NULL)
                 return c;
             }
          return w;
         }
     }
   return NULL;
  }

static void update_cursor ()
  {int id = (hover_win != NULL) ? hover_win->cursor_id : XC_arrow;
   int c  = 0;

   for (size_t i = 0; i < sizeof (cursors) / sizeof (cursors [0]); i++)
     if (x_cursor_glyphs [i].id == id)
        c = (int) i;
   if (c != shown_cursor && cursors [c] != NULL)
      {SDL_SetCursor (cursors [c]);
       shown_cursor = c;
      }
  }

static void set_hover (win *w)
  {if (w == hover_win)
      return;
   if (hover_win != NULL)
      hover_win->mouse_inside = false;                 /* LeaveNotify */
   hover_win = w;
   if (w != NULL)
      w->mouse_inside = true;                          /* EnterNotify */
   update_cursor ();
  }

/* The biggest top level window fills the desktop, all others (dialogs, */
/* menus, the option screen) are centered on top of it.                 */

static void layout ()
  {long best = -1;

   main_win = NULL;
   for (size_t i = 0; i < top_windows.size (); i++)
     {win  *w   = top_windows [i];
      long area = (long) w->w_dx * w->w_dy;

      if (w->is_enable && area > best)
         {best     = area;
          main_win = w;
         }
     }
   if (main_win == NULL)
      return;
   desk_w = 0;
   desk_h = 0;
   for (size_t i = 0; i < top_windows.size (); i++)
     if (top_windows [i]->is_enable)
        {desk_w = std::max (desk_w, top_windows [i]->w_dx);
         desk_h = std::max (desk_h, top_windows [i]->w_dy);
        }
   for (size_t i = 0; i < top_windows.size (); i++)
     {win *w = top_windows [i];

      if (w == main_win)
         {w->pos_x = 0;
          w->pos_y = 0;
         }
      else
         {w->pos_x = std::max (0, (desk_w - w->w_dx) / 2);
          w->pos_y = std::max (0, (desk_h - w->w_dy) / 2);
         }
     }
   mark_dirty ();
   fit_window ();
  }

static void blit_tree (win *w, int ox, int oy, int cx0, int cy0, int cx1, int cy1)
  {canvas *s  = w->surface;
   int    x0 = std::max (cx0, ox);
   int    y0 = std::max (cy0, oy);
   int    x1 = std::min (cx1, ox + s->w);
   int    y1 = std::min (cy1, oy + s->h);

   if (x1 <= x0 || y1 <= y0)
      return;
   for (int y = y0; y < y1; y++)
     memcpy (&frame [(size_t) y * desk_w + x0],
             &s->px [(size_t) (y - oy) * s->w + (x0 - ox)],
             (size_t) (x1 - x0) * sizeof (unsigned int));

   std::map<win *, std::vector<win *> >::iterator k = kids.find (w);

   if (k != kids.end ())
      for (size_t i = 0; i < k->second.size (); i++)
        {win *c = k->second [i];

         if (c->is_enable)
            blit_tree (c, ox + c->pos_x, oy + c->pos_y, x0, y0, x1, y1);
        }
  }

static void draw_border (win *w)
  {for (int b = 1; b <= 2; b++)
     {int x0 = w->pos_x - b;
      int y0 = w->pos_y - b;
      int x1 = w->pos_x + w->w_dx + b - 1;
      int y1 = w->pos_y + w->w_dy + b - 1;

      for (int x = x0; x <= x1; x++)
        for (int y = y0; y <= y1; y += y1 - y0)
          if (x >= 0 && y >= 0 && x < desk_w && y < desk_h)
             frame [(size_t) y * desk_w + x] = black_pixel;
      for (int y = y0; y <= y1; y++)
        for (int x = x0; x <= x1; x += x1 - x0)
          if (x >= 0 && y >= 0 && x < desk_w && y < desk_h)
             frame [(size_t) y * desk_w + x] = black_pixel;
     }
  }

static void present ()
  {if (sdl_win == NULL || desk_w <= 0 || desk_h <= 0)
      return;
   if (tex_w != desk_w || tex_h != desk_h || texture == NULL)
      {if (texture != NULL)
          SDL_DestroyTexture (texture);
       texture = SDL_CreateTexture (renderer, SDL_PIXELFORMAT_RGB888,
                                    SDL_TEXTUREACCESS_STREAMING,
                                    desk_w, desk_h);
       tex_w   = desk_w;
       tex_h   = desk_h;
       frame.assign ((size_t) desk_w * desk_h, desktop_pixel);
      }
   std::fill (frame.begin (), frame.end (), desktop_pixel);
   for (size_t i = 0; i < top_windows.size (); i++)
     {win *w = top_windows [i];

      if (! w->is_enable)
         continue;
      if (w != main_win)
         draw_border (w);
      blit_tree (w, w->pos_x, w->pos_y, 0, 0, desk_w, desk_h);
     }
   SDL_UpdateTexture (texture, NULL, &frame [0], desk_w * sizeof (unsigned int));

   int ow;
   int oh;

   SDL_GetRendererOutputSize (renderer, &ow, &oh);
   SDL_SetTextureScaleMode (texture,
                            (ow % desk_w == 0 && oh % desk_h == 0)
                            ? SDL_ScaleModeNearest : SDL_ScaleModeLinear);
   SDL_SetRenderDrawColor (renderer, 0, 0, 0, 255);
   SDL_RenderClear        (renderer);
   SDL_RenderCopy         (renderer, texture, NULL, NULL);
   SDL_RenderPresent      (renderer);
   if (! shown)
      {SDL_ShowWindow (sdl_win);
       shown = true;
      }
   dirty        = false;
   last_present = SDL_GetTicks ();
  }

