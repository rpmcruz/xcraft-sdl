struct fixed_font
  {int                 w;
   int                 h;
   int                 ascent;
   int                 descent;
   const unsigned char *bits;
  };

static const fixed_font fonts [] =
  {{font6x13_w, font6x13_h, font6x13_ascent, font6x13_descent,
    &font6x13_bits [0][0]},
   {font5x8_w,  font5x8_h,  font5x8_ascent,  font5x8_descent,
    &font5x8_bits [0][0]}};

/* X logical font names look like -foundry-family-weight-slant-setwidth-*/
/* style-PIXELSIZE-...; the game asks for "-misc-*" (the 6x13 "fixed"   */
/* font) and once for pixel size 8 (5x8).                               */

static int font_id_of (const char name [])
  {int field = 0;

   for (const char *p = name; *p != 0; p++)
     if (*p == '-' && ++field == 7)
        return (atoi (p + 1) == 8) ? 1 : 0;
   return 0;
  }

int font_text_width (const char font [], const char s [])
  {return fonts [font_id_of (font)].w * (int) strlen (s);
  }

int font_char_width (const char font [])
  {return fonts [font_id_of (font)].w;
  }

int font_line_height (const char font [])
  {return fonts [font_id_of (font)].ascent + fonts [font_id_of (font)].descent;
  }

