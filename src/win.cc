void win::fill (polyline *p)
  {if (! is_enable || p->n < 3)
      return;

   int y0 = p->p [0].y;
   int y1 = p->p [0].y;

   for (int i = 1; i < p->n; i++)
     {y0 = std::min (y0, (int) p->p [i].y);
      y1 = std::max (y1, (int) p->p [i].y);
     }
   for (int y = y0; y <= y1; y++)
     {std::vector<int> xs;

      for (int i = 0; i < p->n; i++)
        {XPoint a = p->p [i];
         XPoint b = p->p [(i + 1) % p->n];

         if ((a.y <= y && b.y > y) || (b.y <= y && a.y > y))
            xs.push_back (a.x + (int) floor ((double) (y - a.y) *
                                             (b.x - a.x) / (b.y - a.y) + 0.5));
        }
      std::sort (xs.begin (), xs.end ());
      for (size_t i = 0; i + 1 < xs.size (); i += 2)
        for (int x = xs [i]; x < xs [i+1]; x++)
          put (this, surface, x, y, fg_pixel);
     }
   mark_dirty ();
  }

