void win::get_image (XImage *&i, int x, int y, int dx, int dy)
  {if (! is_alien)
      xsync ();
   i         = new XImage;
   i->width  = std::max (0, dx);
   i->height = std::max (0, dy);
   i->data   = new unsigned int [(size_t) i->width * i->height + 1];
   for (int yy = 0; yy < i->height; yy++)
     for (int xx = 0; xx < i->width; xx++)
       i->data [(size_t) yy * i->width + xx] =
         (surface != NULL && surface->inside (x + xx, y + yy))
         ? surface->at (x + xx, y + yy) : black_pixel;
   is_last_pixel = false;
  }

