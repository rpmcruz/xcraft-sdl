static canvas *read_xbm (const char name [])
  {FILE *f = fopen (name, "r");
   char line [512];
   int  w = 0;
   int  h = 0;

   if (f == NULL)
      return NULL;
   while (fgets (line, sizeof (line), f) != NULL && strchr (line, '{') == NULL)
     {char d1 [256];
      char d2 [256];
      int  v;

      if (sscanf (line, "%255s %255s %d", d1, d2, &v) == 3 &&
          strcmp (d1, "#define") == 0)
         {size_t l = strlen (d2);

          if      (l >= 6 && strcmp (d2 + l - 6, "_width")  == 0) w = v;
          else if (l >= 7 && strcmp (d2 + l - 7, "_height") == 0) h = v;
         }
     }
   if (w <= 0 || h <= 0)
      {fclose (f);
       return NULL;
      }

   canvas *c         = new canvas (w, h, true, 0);
   int    row_bytes  = (w + 7) / 8;
   int    n          = 0;
   int    total      = row_bytes * h;
   int    ch;
   char   tok [16];
   int    tl         = 0;

   while (n < total && (ch = fgetc (f)) != EOF)
     {if (isxdigit (ch) || ch == 'x' || ch == 'X')
         {if (tl < 15)
             tok [tl++] = (char) ch;
         }
      else if (tl > 0)
         {tok [tl] = 0;
          int byte = (int) strtol (tok, NULL, 16);
          int y    = n / row_bytes;
          int x0   = (n % row_bytes) * 8;

          for (int b = 0; b < 8; b++)
            if (x0 + b < w && (byte & (1 << b)))
               c->at (x0 + b, y) = 1;
          n++;
          tl = 0;
         }
     }
   fclose (f);
   return c;
  }

static std::map<std::string, canvas *> xbm_cache;

static canvas *cached_xbm (const char name [])
  {std::map<std::string, canvas *>::iterator i = xbm_cache.find (name);

   if (i != xbm_cache.end ())
      return i->second;
   canvas *c = read_xbm (name);
   xbm_cache [name] = c;
   return c;
  }

