void win::ppm (char file_name [], int x, int y, int dx, int dy)
  {char   fname [256];
   FILE   *f;
   XImage *image;

   snprintf (fname, sizeof (fname), "%s.ppm", file_name);
   if ((f = fopen (fname, "w")) == NULL)
      return;
   get_image (image, x, y, dx, dy);
   fprintf (f, "P6\n#%s\n%d %d\n255\n", file_name, dx, dy);
   for (int yy = 0; yy < dy; yy++)
     for (int xx = 0; xx < dx; xx++)
       {int r;
        int g;
        int b;

        get_color (image, xx, yy, r, g, b);
        fprintf   (f, "%c%c%c", r, g, b);
       }
   fclose        (f);
   XDestroyImage (image);
  }
