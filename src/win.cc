/* writes the window area as X bitmap (set bits = not background white) */

void win::store_map (char name [], int x, int y, int dx, int dy)
  {FILE *f = fopen (name, "w");

   if (f == NULL || ! is_enable)
      {if (f != NULL)
          fclose (f);
       return;
      }
   fprintf (f, "#define map_width %d\n#define map_height %d\n", dx, dy);
   fprintf (f, "static char map_bits[] = {\n");
   for (int yy = 0; yy < dy; yy++)
     for (int xb = 0; xb < (dx + 7) / 8; xb++)
       {int byte = 0;

        for (int b = 0; b < 8; b++)
          {int px = x + xb * 8 + b;
           int py = y + yy;

           if (xb * 8 + b < dx && surface->inside (px, py) &&
               surface->at (px, py) != white_pixel)
              byte |= 1 << b;
          }
        fprintf (f, "0x%02x%s", byte,
                 (yy == dy - 1 && xb == (dx + 7) / 8 - 1) ? "};\n" : ",");
       }
   fclose (f);
  }

