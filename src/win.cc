static void disable_tree (win *w)
  {std::map<win *, std::vector<win *> >::iterator k = kids.find (w);

   if (k != kids.end ())
      {std::vector<win *> list = k->second;

       kids.erase (k);
       for (size_t i = 0; i < list.size (); i++)
         {disable_tree (list [i]);
          list [i]->is_enable  = false;
          list [i]->parent_win = NULL;
         }
      }
   forget (w);
  }

