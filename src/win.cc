/* XDrawImageString: the text box is filled with the background first, */
/* the GC function is ignored (always GXcopy)                           */

void win::write (int x, int y, char string [])
  {if (! is_enable)
      return;

   const fixed_font &f    = fonts [font_id];
   int              len   = (int) strlen (string);
   int              func  = gc_function;
   int              top   = y - f.ascent;

   gc_function = GXcopy;
   fill_rect (this, surface, x, top, len * f.w, f.h, bg_pixel);
   for (int i = 0; i < len; i++)
     {const unsigned char *g = f.bits + (size_t) (unsigned char) string [i] * f.h;

      for (int r = 0; r < f.h; r++)
        for (int c = 0; c < f.w; c++)
          if (g [r] & (0x80 >> c))
             put (this, surface, x + i * f.w + c, top + r, fg_pixel);
     }
   gc_function = func;
   mark_dirty ();
  }

