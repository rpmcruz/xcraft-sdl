#!/usr/bin/env python3
"""Extract X11 cursor-font glyphs (shape + mask) into a C++ header.

Usage: cursor2c.py OUT.h cursor.bdf NAME [NAME ...]

Each cursor is stored as SDL_CreateCursor() data: 1 bit per pixel, MSB first,
rows padded to whole bytes, plus the hot spot. The glyphs of the X cursor font
("These glyphs are unencumbered") are placed on a common grid so that the
glyph origin becomes the hot spot, exactly as the X server does.
"""
import sys


def glyphs(path):
    out, name, bbx, rows, in_bitmap = {}, None, None, [], False
    for line in open(path, encoding="latin-1"):
        p = line.split()
        if not p:
            continue
        if p[0] == "STARTCHAR":
            name, bbx, rows, in_bitmap = p[1], None, [], False
        elif p[0] == "ENCODING":
            enc = int(p[-1])
        elif p[0] == "BBX":
            bbx = list(map(int, p[1:5]))
        elif p[0] == "BITMAP":
            in_bitmap = True
        elif p[0] == "ENDCHAR":
            out[name] = (enc, bbx, rows)
            in_bitmap = False
        elif in_bitmap:
            rows.append(int(p[0], 16))
    return out


def pixels(bbx, rows):
    w, h, xoff, yoff = bbx
    nbits = ((w + 7) // 8) * 8
    for r, bits in enumerate(rows):
        for c in range(w):
            if bits & (1 << (nbits - 1 - c)):
                yield xoff + c, r - (yoff + h - 1)


def main():
    out, bdf, names = sys.argv[1], sys.argv[2], sys.argv[3:]
    g = glyphs(bdf)
    with open(out, "w") as o:
        o.write("/* Generated by tools/cursor2c.py from the X11 cursor font (cursor.bdf).\n")
        o.write("   \"These glyphs are unencumbered\". Do not edit. */\n\n")
        o.write("#ifndef xcursors_data_h\n#define xcursors_data_h\n\n")
        o.write("struct x_cursor_glyph\n  {int id, w, h, hot_x, hot_y;\n")
        o.write("   const unsigned char *data;\n   const unsigned char *mask;\n  };\n\n")
        table = []
        for n in names:
            enc, sb, sr = g[n]
            _, mb, mr = g[n + "_mask"]
            shape, mask = set(pixels(sb, sr)), set(pixels(mb, mr))
            pts = shape | mask
            minx = min(x for x, _ in pts)
            miny = min(y for _, y in pts)
            w = max(x for x, _ in pts) - minx + 1
            h = max(y for _, y in pts) - miny + 1
            w8 = (w + 7) // 8 * 8
            for kind, pset in (("data", shape), ("mask", mask)):
                data = []
                for y in range(h):
                    for byte in range(w8 // 8):
                        v = 0
                        for bit in range(8):
                            if (minx + byte * 8 + bit, miny + y) in pset:
                                v |= 0x80 >> bit
                        data.append(v)
                o.write(f"static const unsigned char xcur_{n}_{kind} [] =\n  {{")
                o.write(",".join(f"0x{b:02x}" for b in data))
                o.write("};\n")
            table.append(f"   {{{enc}, {w8}, {h}, {-minx}, {-miny}, xcur_{n}_data, xcur_{n}_mask}}")
            o.write("\n")
        o.write("static const x_cursor_glyph x_cursor_glyphs [] =\n  {\n")
        o.write(",\n".join(table))
        o.write("\n  };\n\n#endif\n")


if __name__ == "__main__":
    main()
