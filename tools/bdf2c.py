#!/usr/bin/env python3
"""Convert fixed-width BDF fonts into a C++ header used by the SDL backend.

Usage: bdf2c.py OUT.h NAME=FILE.bdf [NAME=FILE.bdf ...]

Only code points 0..255 (ISO 8859-1) are kept. Every glyph is rendered into a
full character cell, one byte per row, most significant bit = leftmost pixel.
The X11 misc-fixed fonts this is meant for are in the public domain.
"""
import sys


def parse_bdf(path):
    font = {"glyphs": {}}
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        key = parts[0]
        if key == "FONTBOUNDINGBOX":
            font["w"], font["h"], font["xoff"], font["yoff"] = map(int, parts[1:5])
        elif key == "FONT_ASCENT":
            font["ascent"] = int(parts[1])
        elif key == "FONT_DESCENT":
            font["descent"] = int(parts[1])
        elif key == "STARTCHAR":
            enc, bbx, rows = None, None, []
            for gl in lines:
                gp = gl.split()
                if gp[0] == "ENCODING":
                    enc = int(gp[1])
                elif gp[0] == "BBX":
                    bbx = list(map(int, gp[1:5]))
                elif gp[0] == "BITMAP":
                    for bl in lines:
                        if bl.strip() == "ENDCHAR":
                            break
                        rows.append(int(bl.strip(), 16) if bl.strip() else 0)
                    break
            if enc is not None and 0 <= enc <= 255:
                font["glyphs"][enc] = (bbx, rows)
    return font


def render(font, bbx, rows):
    w, h, ascent = font["w"], font["h"], font["ascent"]
    gw, gh, gx, gy = bbx
    cell = [0] * h
    nbytes = (gw + 7) // 8
    top = ascent - (gy + gh)  # row in the cell of the glyph's first bitmap row
    for r, bits in enumerate(rows):
        cy = top + r
        if not 0 <= cy < h:
            continue
        for c in range(gw):
            if bits & (1 << (nbytes * 8 - 1 - c)):
                cx = gx - font["xoff"] + c
                if 0 <= cx < w and cx < 8:
                    cell[cy] |= 0x80 >> cx
    return cell


def main():
    out = sys.argv[1]
    specs = [a.split("=", 1) for a in sys.argv[2:]]
    with open(out, "w") as o:
        o.write("/* Generated by tools/bdf2c.py from the X11 misc-fixed BDF fonts.\n")
        o.write("   The misc-fixed fonts are in the public domain. Do not edit. */\n\n")
        o.write("#ifndef fixedfont_data_h\n#define fixedfont_data_h\n\n")
        for name, path in specs:
            font = parse_bdf(path)
            if font["w"] > 8:
                sys.exit(f"{path}: only fonts up to 8 pixels wide are supported")
            o.write(f"static const int  {name}_w = {font['w']};\n")
            o.write(f"static const int  {name}_h = {font['h']};\n")
            o.write(f"static const int  {name}_ascent = {font['ascent']};\n")
            o.write(f"static const int  {name}_descent = {font['descent']};\n")
            o.write(f"static const unsigned char {name}_bits [256][{font['h']}] =\n  {{\n")
            for code in range(256):
                g = font["glyphs"].get(code)
                cell = render(font, *g) if g else [0] * font["h"]
                o.write("   {" + ",".join(f"0x{b:02x}" for b in cell) + "},")
                o.write(f" /* {code} */\n")
            o.write("  };\n\n")
        o.write("#endif\n")


if __name__ == "__main__":
    main()
